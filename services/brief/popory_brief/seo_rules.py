# 모든 브리핑 카테고리 시스템 프롬프트 뒤에 붙는 공통 검색 유입(SEO) 규칙.
#
# 카테고리 SKILL.md 마다 같은 규칙을 복제하면 한 곳만 고쳐지고 나머지가 옛 형식으로 남는다.
# 그래서 제목·소제목·키워드 배치·시각 자료 규칙은 여기 한 곳에 두고 generate_brief.py 가
# 카테고리별 값(발행 꼬리·카테고리명)을 채워 시스템 프롬프트 끝에 덧붙인다. SKILL.md 는
# 자기 분야의 수집·문체 규칙만 갖는다. 규칙의 배경은 seo_title.py 머리 주석 참조.
from __future__ import annotations

import datetime

from popory_brief.categories import Category
from popory_brief.seo_title import RECOMMENDED_MAX

_TEMPLATE = """

## 검색 유입(SEO) 공통 규칙 — 위 형식 지시보다 우선한다

이 글은 포털 아카이브와 네이버 블로그에 그대로 올라간다. 네이버·구글 검색 봇은 제목의 **가장 왼쪽(첫 15자)** 에 가장 높은 키워드 가중치를 주고, 소제목(H태그) 단위로 단락 주제를 읽어 스마트블록·스니펫에 노출한다. 검색자는 "{name} 브리핑" 이 아니라 그날의 구체 이슈("개포우성7차 통합심의", "종부세 1주택 실거주 공제")를 검색창에 친다.

### 제목 (meta_json.title)
- 형식. `{{핵심 검색 키워드 1~2개}} {{핵심 팩트 요약}} | {suffix}`
- 예. `개포우성7차 가락삼익 재건축 통과와 코인 매각 주택 매수 분석 | 9월 1주차 부동산 브리핑`
- 제목 맨 앞은 **그날 가장 중요한 이슈의 고유 검색어**(정책명·단지명·기관명·제도명)로 시작한다. `[{name} 브리핑]` 같은 말머리, `{date}` 같은 날짜, `①` 같은 순번 기호를 앞에 두지 않는다. 시스템이 앞의 말머리·날짜를 걷어내고 `| {suffix}` 꼬리를 붙이므로 꼬리는 그대로 두면 된다.
- `|` 앞부분은 검색자가 실제로 칠 단어의 조합으로 쓰고, 전체 {max_len}자 안팎을 넘기지 않는다.
"""

_BODY_TEMPLATE = """
### 본문 소제목 (H태그)
- 본문은 **헤딩 없는 도입 2~3문장**으로 시작한다. 이 첫 3줄 안에 제목의 핵심 키워드가 1회 들어간다.
- 이슈·주제마다 반드시 `##`/`###` 소제목을 둔다. 소제목은 굵은 본문 텍스트로 대체하지 않는다 — 볼드는 검색 봇에 소제목이 아니다.
- 각 소제목에는 그 단락의 검색 키워드(정책명·단지명·수치)가 들어가고, 소제목 바로 아래 첫 문장이 그 소제목의 답이 되게 쓴다.
- 본문 끝에 `## 정리` 소제목을 두고 1~2문장으로 닫는다. 이 결론에도 핵심 키워드가 1회 들어간다.
- 핵심 키워드는 도입 1회 + 관련 소제목 + 결론 1회, 글 전체에 **4~6회** 자연스럽게 반복한다. 그 이상 억지로 넣지 않는다.

### 시각 자료
- 긴 글은 텍스트만으로 체류시간이 유지되지 않는다. 수치가 나오는 이슈(금리·시세·거래량·일정·세율·비교)는 GFM 표(`| 항목 | 값 |`)로 정리해 본문에 **2개 이상** 둔다. 표 위 한 줄에 표의 제목과 출처(기관명·기준일)를 굵게 적는다.
- 표는 원문 수치 그대로, 없는 수치를 채우지 않는다.

### 자가 점검 (형식 점검 항목에 추가)
- [ ] title 이 고유 검색어로 시작하고 말머리·날짜·순번으로 시작하지 않음
- [ ] 본문이 헤딩 없는 도입 2~3문장으로 시작하고, 첫 3줄에 핵심 키워드 포함
- [ ] 이슈마다 `##`/`###` 소제목 존재, 끝에 `## 정리`
- [ ] 수치 표 2개 이상
"""


_TITLE_ONLY_CHECK = """
### 자가 점검 (형식 점검 항목에 추가)
- [ ] title 이 고유 검색어로 시작하고 말머리·날짜·순번으로 시작하지 않음
"""


def seo_rules(category: Category, d: datetime.date) -> str:
    """카테고리 시스템 프롬프트 끝에 덧붙일 공통 SEO 규칙. seo_body=false 카테고리는 제목 규칙만."""
    text = _TEMPLATE.format(name=category.name, suffix=category.title_suffix(d),
                            date=d.strftime("%Y-%m-%d"), max_len=RECOMMENDED_MAX)
    return text + (_BODY_TEMPLATE if category.seo_body else _TITLE_ONLY_CHECK)
