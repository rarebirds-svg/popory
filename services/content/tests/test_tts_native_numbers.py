# 고유어 수사 — 단위에 따라 "세 가지·서른일곱 개·스무 명" 으로 읽는다. 대본 34건 스캔(2026-10)에서 나온 실사례와,
# 규칙을 그대로 적용하면 새로 틀리는 경우(개월·대·달러·제N권…)를 함께 고정한다.
import pytest

from popory_content.tts import _native_korean, _to_ssml, _prep_text, spoken_text


@pytest.mark.parametrize("n,want", [
    (1, "한"), (2, "두"), (3, "세"), (4, "네"), (5, "다섯"), (9, "아홉"),
    (10, "열"), (11, "열한"), (12, "열두"), (14, "열네"),
    (20, "스무"), (21, "스물한"), (24, "스물네"), (37, "서른일곱"), (99, "아흔아홉"),
])
def test_native_korean_forms(n, want):
    assert _native_korean(n) == want


@pytest.mark.parametrize("text,want", [
    # 스캔에서 확인된 실사례
    ("3가지 원칙", "세 가지 원칙"),
    ("6가지와 7가지", "여섯 가지와 일곱 가지"),
    ("37개의 사례", "서른일곱 개의 사례"),
    ("3~5명이 참석했다.", "세 명에서 다섯 명이 참석했다."),
    # 시각·시간 — 요청서 빈도표엔 없었지만 같은 규칙으로 잡힌다
    ("3시 30분", "세 시 삼십분"),
    ("오전 7시에 일어난다", "오전 일곱 시에 일어난다"),
    ("24시간 동안", "스물네 시간 동안"),
    # 20 은 스무, 21 부터는 스물한
    ("20명과 21명", "스무 명과 스물한 명"),
    # 100 이상은 한자어, 단위와는 띄운다
    ("100개와 1,700명", "백 개와 천칠백 명"),
    ("83살", "여든세 살"),
    ("3번 말했다", "세 번 말했다"),
    ("3번째 시도", "세 번째 시도"),
    ("2달 전", "두 달 전"),
    ("3 가지", "세 가지"),                    # 이미 띄어 있으면 공백을 더 넣지 않는다
    ("10~20개", "열 개에서 스무 개"),
])
def test_native_numerals_before_counting_units(text, want):
    assert spoken_text(text) == want


@pytest.mark.parametrize("text,want", [
    # 월: 6월·10월만 예외, 나머지는 한자어 그대로
    ("6월과 10월 그리고 12월", "유월과 시월 그리고 십이월"),
    ("2025년 9월 5일", "이천이십오년 구월 오일"),
])
def test_months(text, want):
    assert spoken_text(text) == want


@pytest.mark.parametrize("text,want", [
    # 규칙을 그대로 적용하면 새로 틀리는 경우 — 한자어로 남아야 한다
    ("3개월 동안", "삼개월 동안"),               # 개월은 한자어. 고유어는 '달' 일 때만
    ("3개국", "삼개국"),
    ("3대 기업", "삼대 기업"),                   # 대는 목록에서 뺐다
    ("3달러", "삼달러"),                         # '달러' 의 달은 단위가 아니다
    ("1번 항목을 보라", "일번 항목을 보라"),       # 번호 이름
    ("제1권과 제3장", "제일권과 제삼장"),          # 서수(순서)는 한자어
    ("1차 2차 3차", "일차 이차 삼차"),
    ("16년 전", "십육년 전"),
    ("12% 올랐다", "십이퍼센트 올랐다"),
    ("30분 걸렸다", "삼십분 걸렸다"),
    ("83세의 노인", "팔십삼세의 노인"),
    ("3.5개", "삼점오개"),                       # 소수는 기존 규칙 그대로
    ("B2B 2대", "B이B 이대"),                    # 알파벳 바로 뒤 숫자는 기존 동작 유지
])
def test_units_that_must_stay_sino(text, want):
    assert spoken_text(text) == want


def test_zero_stays_sino():
    assert spoken_text("0명") == "영 명"


def test_ssml_path_uses_the_same_rule_as_subtitle_timing():
    """자막 타이밍(spoken_text)과 실제 합성(_to_ssml)이 같은 변환을 써야 길이 계산이 어긋나지 않는다."""
    for text in ("3가지와 20명", "3~5명", "6월 7시에 37개"):
        assert _to_ssml(_prep_text(text)) == f"<speak>{spoken_text(text)}</speak>"


# --- 번(番): 횟수 문맥에서만 고유어 ---------------------------------------------------------------------------
# "3번 말했다" 는 "세 번", "1번 법칙" 은 "일 번". 숫자 뒤 글자만으로는 못 가르므로 횟수로 읽히는 문맥(활용형·횟수 서술어)에서만
# 고유어를 쓰고, 번호 매김 명사가 따르면 한자어로 둔다. 틀려도 덜 어색한 쪽(한자어)으로 기운다.
@pytest.mark.parametrize("text,want", [
    # 활용형이 바로 붙는다
    ("5번째 방법", "다섯 번째 방법"),
    ("세 번씩", "세 번씩"),
    ("2번이나 실패했다", "두 번이나 실패했다"),
    ("4번이고 그리고", "네 번이고 그리고"),
    ("한 번도 못 했다", "한 번도 못 했다"),
    ("3번 정도", "세 번 정도"),
    # 띄어 쓴 뒤 횟수 서술어·부사
    ("3번 말했다", "세 번 말했다"),
    ("3번 읽었다", "세 번 읽었다"),
    ("3번 다시 봤다", "세 번 다시 봤다"),
    ("3번 반복", "세 번 반복"),
    ("10번 넘게 시도했다", "열 번 넘게 시도했다"),
    # 범위의 한쪽이 횟수면 양쪽 모두
    ("2~3번 말했다", "두 번에서 세 번 말했다"),
    ("2~3번째", "두 번에서 세 번째"),
])
def test_beon_is_native_only_in_counting_context(text, want):
    assert spoken_text(text) == want


@pytest.mark.parametrize("noun", ["법칙", "원칙", "단계", "방법", "전략", "규칙", "질문", "장", "항목", "문제"])
def test_beon_before_numbering_nouns_stays_sino(noun):
    """번호 매김 명사가 따르면 "일 번 법칙" 이 아니라 "일번 법칙" — 반례 목록(법칙·원칙·단계·방법·전략·규칙·질문·장 …)."""
    out = spoken_text(f"2번 {noun}")
    assert out == f"이번 {noun}"
    assert "두 번" not in out


@pytest.mark.parametrize("text,want", [
    ("정답은 3번.", "정답은 삼번."),            # 문장 끝 "N번" 은 번호 이름일 가능성이 높다
    ("1번을 선택하세요", "일번을 선택하세요"),
    ("1번에서 3번까지 문제", "일번에서 삼번까지 문제"),   # 번호 범위는 한자어(횟수 범위 "2~3번 말했다" 와 다르다)
    ("1번, 2번, 3번", "일번, 이번, 삼번"),
    ("1번 보고서", "일번 보고서"),              # '보고' 가 아니라 '보고서' 는 횟수 서술어가 아니다
    ("정답은 5번이다", "정답은 오번이다"),         # 서술격조사 '이다' 는 번호를 가리킨다("이고" 와 다르다)
])
def test_beon_outside_counting_context_stays_sino(text, want):
    assert spoken_text(text) == want


# --- 소수가 낀 범위 ---------------------------------------------------------------------------------------------
@pytest.mark.parametrize("text,want", [
    # 요청 케이스. 소수는 고유어로 못 읽으므로 단위를 나누지 않고 뒤 정수에만 단위를 붙인다.
    ("연 6.5~7%의 수익률", "연 육점오에서 칠퍼센트의 수익률"),
    ("3.5~4개", "삼점오에서 네 개"),
    # 같은 원인의 변형
    ("3.5~4시간 걸린다", "삼점오에서 네 시간 걸린다"),
    ("3~3.5개", "삼에서 삼점오개"),
    ("1.5~2배", "일점오에서 이배"),
])
def test_ranges_with_decimals(text, want):
    assert spoken_text(text) == want


def test_decimal_range_does_not_split_a_decimal_into_integers():
    """회귀: 범위 정규식이 3.5 의 5 만 붙잡아 "3.5개에서 4개"(삼점오개에서 네 개)를 만들었다."""
    from popory_content.tts import _prep_text
    assert _prep_text("3.5~4개") == "3.5에서 4개"
    assert "삼점오개" not in spoken_text("3.5~4개")


# --- 권(卷): 권차라서 한자어 ---------------------------------------------------------------------------------
# 권은 권수("책 3권")와 권차("1권·2권" = 시리즈의 몇 번째 권)가 같은 글자다. 실제 대본(채사장 『지적 대화를 위한 넓고
# 얕은 지식』)에 나오는 "1권, 2권" 은 전부 권차라서 "일 권·이 권" 으로 읽혀야 한다 — 고유어("한 권")는 오독이다.
@pytest.mark.parametrize("text,want", [
    ("1권의 부제는 지식입니다", "일권의 부제는 지식입니다"),
    ("1권과 달리 2권은 더 어렵다", "일권과 달리 이권은 더 어렵다"),
    ("이 2권까지 읽으면 된다", "이 이권까지 읽으면 된다"),
    ("1권, 2권을 읽었다.", "일권, 이권을 읽었다."),
    ("제1권과 제3장", "제일권과 제삼장"),
    ("10권짜리 전집", "십권짜리 전집"),          # 권수처럼 보여도 권은 가르지 않는다(권차와 같은 글자)
])
def test_gwon_stays_sino_because_it_is_a_volume_number(text, want):
    assert spoken_text(text) == want


def test_gwon_does_not_affect_other_native_units_in_the_same_sentence():
    assert spoken_text("1권의 3가지 원칙") == "일권의 세 가지 원칙"
