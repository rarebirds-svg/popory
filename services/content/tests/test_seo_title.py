# 블로그 제목 말머리 제거 — `[책 리뷰]` 류를 앞에서 걷어내고, 남는 게 없으면 원문 유지.
import pytest

from popory_content.seo_title import strip_prefix


@pytest.mark.parametrize("raw, want", [
    ("[책 리뷰] 사이토 히토리,1퍼센트 부자의 법칙:이 말을 하기 시작하면 당신은 부자가 될 것입니다",
     "사이토 히토리,1퍼센트 부자의 법칙:이 말을 하기 시작하면 당신은 부자가 될 것입니다"),
    ("【서평】 [추천] 돈의 심리학 핵심 요약", "돈의 심리학 핵심 요약"),
    ("책 리뷰 | 돈의 심리학 핵심 요약 및 서평", "돈의 심리학 핵심 요약 및 서평"),
    ("서평: 돈의 심리학", "돈의 심리학"),
    ("북리뷰 - 부자 아빠 가난한 아빠", "부자 아빠 가난한 아빠"),
    ("(리뷰) 돈의 심리학", "돈의 심리학"),
    ("사이토 히토리 1퍼센트 부자의 법칙 핵심 요약 및 서평: 말버릇 하나로 인생을 바꾸는 1천 번의 법칙",
     "사이토 히토리 1퍼센트 부자의 법칙 핵심 요약 및 서평: 말버릇 하나로 인생을 바꾸는 1천 번의 법칙"),
    ("돈의 심리학 서평: 부는 보이지 않는다", "돈의 심리학 서평: 부는 보이지 않는다"),  # 중간의 '서평:' 은 건드리지 않는다
    ("[책 리뷰]", "[책 리뷰]"),   # 걷어내면 빈 제목 — 원문 유지
    ("", ""),
])
def test_strip_prefix(raw, want):
    assert strip_prefix(raw) == want
