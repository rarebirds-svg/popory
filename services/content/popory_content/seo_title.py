# 블로그 제목의 검색 유입(SEO) 정규화 — 말머리를 앞에서 걷어낸다.
#
# 배경(2026-09-06 제미나이 검토). 네이버·구글 검색 봇은 제목의 **가장 왼쪽(첫 15자)** 에 가장 높은
# 키워드 가중치를 준다. `[책 리뷰] 사이토 히토리, 1퍼센트 부자의 법칙: …` 처럼 검색자가 치지 않는
# 말머리가 앞단을 차지하면 책 제목·저자가 뒤로 밀린다. 제목은 `{저자} {책제목} 핵심 요약 및 서평: {훅}`
# 처럼 검색 수요가 높은 롱테일(핵심 요약·서평·줄거리·책 추천)과 책·저자를 앞에 둔다.
#
# 규칙은 prompt.py(생성)·seo_review.py(검토)에 있지만, 스타일 샘플이나 습관으로 말머리가 다시 붙는
# 일이 있어 워커가 review 로 넘기기 직전에 한 번 더 결정적으로 걷어낸다(names.py 와 같은 원칙).
# 제목을 새로 짓거나 줄이지는 않는다 — 걷어낸 뒤 남는 게 없으면 원문을 그대로 둔다.
import re

# `[책 리뷰]`·`【서평】`·`(리뷰)` 같은 말머리. 여러 개 붙어도 전부.
_LEADING_BRACKET = re.compile(r"^\s*(?:[\[【][^\]】]{1,20}[\]】]\s*|\([^)]{1,12}\)\s*)+")
# `책 리뷰 | …`, `서평: …`, `북리뷰 - …` 처럼 구분 기호로 붙인 말머리. 짧은 고정어만 잡는다.
_LEADING_LABEL = re.compile(r"^\s*(?:책\s?리뷰|북\s?리뷰|서평|책\s?추천|도서\s?리뷰|독후감|리뷰)\s*[:|\-–—]\s*")
# 네이버 블로그 제목 상한은 100자, 검색 결과에서 잘리지 않는 안전선은 60자 안팎이다.
RECOMMENDED_MAX = 60


def strip_prefix(title: str) -> str:
    """제목 앞의 `[말머리]`·`책 리뷰:` 류를 걷어낸다. 남는 게 없으면 원문 그대로."""
    t = (title or "").strip()
    while True:
        before = t
        t = _LEADING_BRACKET.sub("", t)
        t = _LEADING_LABEL.sub("", t)
        if t == before:
            break
    t = t.strip(" \t:|-–—")
    return t if t else (title or "").strip()
